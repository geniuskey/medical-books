#!/usr/bin/env python3
"""Generate the shelf catalog from migration/books.json, roadmap.json and the map in book.json.

Chapters and simulators are counted from each book's chapters/*.html.
Writes catalog.js for this site and catalog.json for books.euiyun.com (its tools/sync-books.py).
"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
shelf = json.loads((ROOT / 'book.json').read_text())
manifest = json.loads((ROOT / 'migration/books.json').read_text())
FIELDS = ('id', 'title', 'subtitle', 'headline', 'description', 'stage', 'status', 'color', 'colorDark',
          'topics', 'motif', 'code', 'slug')
catalog = []
for book in manifest['books']:
    entry = {k: book[k] for k in FIELDS}
    entry['url'] = book['slug'] + '/'
    # The individual sites are retired; readers find the books only on this shelf.
    entry['legacyUrl'] = None
    pages = list((ROOT / book['slug'] / 'chapters').glob('*.html'))
    entry['chapters'] = len(pages)
    entry['simulators'] = sum(p.read_text().count('class="sim"') for p in pages)
    catalog.append(entry)
published = len(catalog)
catalog.extend(json.loads((ROOT / 'roadmap.json').read_text()))

# The map groups books by stage; every book sits in exactly one group.
shelf_map = shelf['map']
stages = {group['id'] for group in shelf_map['groups']}
ids = {book['id'] for book in catalog}
missing = [book['id'] for book in catalog if book['stage'] not in stages]
assert not missing, f'Books without a map group: {missing}'
for a, b, reason in shelf_map['links']:
    assert a in ids and b in ids and a != b and reason.strip(), f'Bad map link: {a} → {b}'

dump = lambda value: json.dumps(value, ensure_ascii=False, indent=2)
shelf_info = {key: shelf[key] for key in ('id', 'title', 'url')} | {'coverTitles': shelf.get('coverTitles', {})}
(ROOT / 'catalog.js').write_text('/* Generated by tools/sync-catalog.py. Text: CC BY 4.0. */\n'
                                 f'window.MEDICAL_BOOKS = {dump(catalog)};\nwindow.MEDICAL_MAP = {dump(shelf_map)};\n'
                                 # shared/js/shelf.js(공통 파일)가 읽는 서가 설정
                                 f'window.SHELF = Object.assign({dump(shelf_info)}, {{ books: window.MEDICAL_BOOKS, map: window.MEDICAL_MAP }});\n')
(ROOT / 'catalog.json').write_text(dump({
    'format': 'euiyun-shelf/1',
    'shelf': {key: shelf[key] for key in ('id', 'title', 'url', 'field')},
    'map': shelf_map,
    'books': catalog,
}) + '\n')
print(f'Catalog: {published} published, {len(catalog) - published} planned')
